/** عمليات نقية على القوالب: تحقق سليمية وتوليد مسودات الفقرات — قابلة للاختبار بلا واجهة. */
object ScriptTemplatesLogic {

    /** فقرات القالب كأزواج (عنوان، نص) جاهزة للتمرير إلى ScriptStore.addAll. */
    fun drafts(template: ScriptTemplate): List<Pair<String, String>> =
        template.sections.map { it.title to it.body }

    /** رسالة خطأ عربية عند عيب في القالب، أو null إن كان سليمًا. */
    fun validate(template: ScriptTemplate): String? = when {
        template.id.isBlank() -> "معرف القالب فارغ"
        template.name.isBlank() -> "اسم القالب فارغ"
        template.description.isBlank() -> "وصف القالب «${template.name}» فارغ"
        template.sections.isEmpty() -> "قالب «${template.name}» بلا فقرات"
        template.sections.any { it.title.isBlank() } -> "قالب «${template.name}» فيه فقرة بلا عنوان"
        template.sections.any { it.body.isBlank() } -> "قالب «${template.name}» فيه فقرة بلا نص"
        else -> null
    }

    /** أخطاء الكتالوج كاملًا — فارغة يعني القوالب كلها سليمة. */
    fun catalogErrors(): List<String> =
        ScriptTemplateCatalog.all.mapNotNull { validate(it) }

    /**
     * محارف القوالب التي لا يغطيها خط تصدير PDF (تظهر مربعات في الملف):
     * الحساب حي من الخط المدمج نفسه فلا يمر محرف غير مدعوم إلى الملف أبدًا.
     */
    fun pdfUnsafeChars(): List<String> {
        val found = sortedSetOf<String>()
        ScriptTemplateCatalog.all.forEach { t ->
            val text = t.name + t.description + t.sections.joinToString("") { it.title + it.body }
            found.addAll(ScriptPdfExporter.missingGlyphs(text))
        }
        return found.toList()
    }
}
