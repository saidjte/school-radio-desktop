 * حقيقية يختار المعلم منها فيُولَّد السكريبت بفقراته في ثانية.
 * كل نص يحمل جملًا جاهزة للقراءة على الهواء مع أقواس [إرشاد] يملؤها المذيع.
 * علامات الترقيم هنا آمنة لخط تصدير PDF (لا شرطات طويلة ولا علامات غير مغطاة).
 */
data class ScriptTemplateSection(
    val title: String,
    val body: String
)

data class ScriptTemplate(
    val id: String,
    val name: String,
    val description: String,
    val sections: List<ScriptTemplateSection>
) {
    val sectionCount: Int get() = sections.size

    fun totalWords(): Int =
        sections.sumOf { ScriptStats.wordCount(it.title) + ScriptStats.wordCount(it.body) }

    /** زمن القراءة التقديري للقالب كاملًا بالثواني. */
    fun estimatedSeconds(): Long = sections.sumOf { ScriptStats.secondsFor(it.body) }
}

